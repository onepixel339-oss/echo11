export const VOCAB: Record<string, VocabEntry> = { ...GENRES, ...TAGS };
export { GENRES, TAGS };

export function vocabLabel(slug: string, lang: "en" | "ar"): string {
  const entry = VOCAB[slug];
  if (entry) return lang === "ar" ? entry.ar : entry.en;
  // prettify unknown provider slugs: "time-manipulation" → "Time Manipulation"
  return slug
    .split("-")
    .map((w) => (w ? w[0].toUpperCase() + w.slice(1) : w))
    .join(" ");
}
