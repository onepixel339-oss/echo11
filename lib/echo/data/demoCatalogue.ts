export interface DemoSeed {
  id: string;
  mediaType: MediaType;
  format: MediaFormat;
  title: string;
  titleAr?: string;
  /** original-language title or romanization (improves search matching) */
  originalTitle?: string;
  year: number;
  genres: string[];
  tags: string[];
  creators?: string[];
  studios?: string[];
  languages?: string[];
  countries?: string[];
  /** approximate where present; curated collection entries omit it */
  contentRating?: string;
  runtimeMinutes?: number;
  episodeCount?: number;
  synopsis: string;
  synopsisAr: string;
  franchise?: string;
  /** overrides the default source attribution (curated collections) */
  attribution?: string;
  /** which part of the local catalogue this seed belongs to (pools weave
   *  curated classics and demo-universe titles so shelves span eras) */
  collection?: "demo" | "curated";

  /* ---- v3 print-media fields (manga / comics / some books; optional) ---- */
  /** fine-grained form: manga, manhwa, manhua, one-shot, light-novel,
   *  comic-strip, comic-series, comic-issue, graphic-novel, collected-edition */
  subtype?: string;
  publicationStatus?: PublicationStatus;
  /** settled volume/chapter/issue counts (completed runs only) */
  volumeCount?: number;
  chapterCount?: number;
  issueCount?: number;
  /** issue number for an individual comic-issue record */
  issueNumber?: number;
  /** publication end year, when verified */
  endYear?: number;
}

