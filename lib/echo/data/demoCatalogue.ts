/** Convert a demo seed into the normalized MediaItem shape. */
export function demoToMediaItem(seed: DemoSeed): MediaItem {
  // The local catalogue is ECHO's own approved data (registry: "echo-demo"),
  // so it carries the same v2 provenance stamp as every other record.
  return stampCatalogProvenance({
    localId: `echo-demo:${seed.id}`,
    provider: "echo-demo",
    providerId: seed.id,
    mediaType: seed.mediaType,
    format: seed.format,
    title: seed.title,
    titleAr: seed.titleAr,
    originalTitle: seed.originalTitle,
    synopsis: seed.synopsis,
    synopsisAr: seed.synopsisAr,
    releaseYear: seed.year,
    releaseDate: `${seed.year}`,
    genres: seed.genres,
    tags: seed.tags,
    creators: seed.creators,
    studios: seed.studios,
    languages: seed.languages,
    countries: seed.countries,
    contentRating: seed.contentRating,
    runtimeMinutes: seed.runtimeMinutes,
    episodeCount: seed.episodeCount,
    // v3 print-media fields
    subtype: seed.subtype,
    publicationStatus: seed.publicationStatus,
    volumeCount: seed.volumeCount,
    chapterCount: seed.chapterCount,
    issueCount: seed.issueCount,
    issueNumber: seed.issueNumber,
    endYear: seed.endYear,
    sourceAttribution:
      seed.attribution ?? "ECHO demo catalogue (approximate development data)",
    metadataFetchedAt: new Date(0).toISOString(),
  });
}

export const DEMO_MEDIA: MediaItem[] = DEMO_CATALOGUE.map(demoToMediaItem);

